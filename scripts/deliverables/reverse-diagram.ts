import { Project } from 'ts-morph';
import { mkdir, writeFile } from 'node:fs/promises';
import { relative, resolve } from 'node:path';

// AST-derived overview: a reproducible complement to the curated service diagram.
const root = resolve('.');
const project = new Project({
  skipAddingFilesFromTsConfig: true,
  compilerOptions: { noResolve: true },
});
project.addSourceFilesAtPaths(['packages/core/src/**/*.ts', 'apps/server/src/**/*.ts']);
const declarations = project
  .getSourceFiles()
  .filter((f) => !f.getFilePath().endsWith('.test.ts'))
  .flatMap((file) => [
    ...file
      .getClasses()
      .filter((c) => c.isExported())
      .map((c) => ({
        name: c.getName()!,
        kind: 'class',
        file: relative(root, file.getFilePath()),
        methods: c.getMethods().map((m) => m.getName()),
      })),
    ...file
      .getInterfaces()
      .filter(
        (c) =>
          c.isExported() &&
          ['LlmAdapter', 'RepoReader', 'OrchestratorPorts', 'GitHubDeliveryPort'].includes(
            c.getName(),
          ),
      )
      .map((c) => ({
        name: c.getName(),
        kind: 'interface',
        file: relative(root, file.getFilePath()),
        methods: c.getMethods().map((m) => m.getName()),
      })),
  ])
  .sort((a, b) => a.file.localeCompare(b.file) || a.name.localeCompare(b.name));
const lines = ['classDiagram', '  direction LR'];
for (const d of declarations) {
  lines.push(
    `  class ${d.name} {`,
    ...(d.kind === 'interface' ? ['    <<interface>>'] : []),
    ...d.methods.map((m) => `    +${m}()`),
    '  }',
  );
}
for (const file of project.getSourceFiles())
  for (const c of file.getClasses()) {
    if (!declarations.some((d) => d.name === c.getName())) continue;
    for (const parent of c.getImplements())
      if (declarations.some((d) => d.name === parent.getText()))
        lines.push(`  ${c.getName()} ..|> ${parent.getText()}`);
  }
await mkdir('docs/diagrams', { recursive: true });
await writeFile(
  'docs/diagrams/reverse-engineered.md',
  [
    '# Reverse-engineered exported classes and selected ports',
    '',
    '<!-- Generated by npm run diagrams:reverse from the TypeScript AST. -->',
    '',
    '![AST-derived classes](png/reverse-engineered.png)',
    '',
    '```mermaid',
    ...lines,
    '```',
    '',
    '| Declaration | Kind | Source |',
    '| --- | --- | --- |',
    ...declarations.map((d) => `| ${d.name} | ${d.kind} | [${d.file}](../../${d.file}) |`),
    '',
    'The curated diagram includes function-based stage services, database entities and the React view.',
    'This AST-derived diagram includes exported classes and selected adapter interfaces, with declared',
    'methods and explicit implements relationships. It intentionally does not infer runtime dependency',
    'injection, function-call relationships, database relationships, or UI components as classes.',
    '',
  ].join('\n'),
);
console.log(`Extracted ${declarations.length} declarations from source`);
