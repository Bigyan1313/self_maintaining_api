/** Generate a unit-test inventory from actual Vitest JSON and V8 coverage reports. */
import { spawnSync, execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { resolve, relative } from 'node:path';

const root = resolve('.');
const groups = ['packages/core', 'apps/server', 'apps/web', 'demo/api', 'scripts', 'scenarios'];
// Increment 16 owns this workspace; include it automatically once its tests land.
const evaluation = JSON.parse(readFileSync('eval/package.json', 'utf8')) as {
  scripts?: { test?: string };
};
if (evaluation.scripts?.test) groups.push('eval');
const selected = process.argv.slice(2);
if (selected.some((g) => !groups.includes(g))) throw new Error('Unknown test group');
const rows: string[] = [];
const files: string[] = [];
let failed = false;
for (const group of groups) {
  if (selected.length && !selected.includes(group)) {
    rows.push(`| ${group} | NOT RUN | — | — | — | — |`);
    continue;
  }
  const out = resolve('coverage', group.replaceAll('/', '-'));
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  const run = spawnSync(
    resolve('node_modules/.bin/vitest'),
    [
      'run',
      '--coverage',
      '--coverage.reporter=json-summary',
      '--coverage.reporter=text',
      `--coverage.reportsDirectory=${out}`,
      '--reporter=default',
      '--reporter=json',
      `--outputFile.json=${out}/tests.json`,
    ],
    { cwd: resolve(group), stdio: 'inherit', env: process.env },
  );
  if (run.status !== 0) failed = true;
  try {
    const report = JSON.parse(readFileSync(`${out}/tests.json`, 'utf8')) as {
      numPassedTests: number;
      numTotalTests: number;
      numPendingTests: number;
      testResults: { name: string; assertionResults: { status: string }[] }[];
    };
    const coverage = JSON.parse(readFileSync(`${out}/coverage-summary.json`, 'utf8')) as {
      total: Record<'lines' | 'branches' | 'functions' | 'statements', { pct: number }>;
    };
    rows.push(
      `| ${group} | ${report.numPassedTests}/${report.numTotalTests} (${report.numPendingTests} skipped) | ${coverage.total.lines.pct}% | ${coverage.total.branches.pct}% | ${coverage.total.functions.pct}% | ${coverage.total.statements.pct}% |`,
    );
    files.push(
      `\n## ${group}\n`,
      ...report.testResults.map((t) => {
        const path = relative(root, t.name);
        return `- [${path}](../${path}): ${t.assertionResults.filter((a) => a.status === 'passed').length}/${t.assertionResults.length} passed`;
      }),
    );
  } catch {
    failed = true;
    rows.push(`| ${group} | REPORT MISSING / FAILED | — | — | — | — |`);
  }
}
const commit = execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
writeFileSync(
  'docs/unit-tests.md',
  [
    '# Unit tests and coverage',
    '',
    '<!-- Generated by npm run test:coverage; do not transcribe counts. -->',
    '',
    `Executed ${new Date().toISOString()} on ${process.platform}, Node ${process.version}, commit ${commit}.`,
    `Working tree changed: ${Boolean(execFileSync('git', ['status', '--porcelain'], { encoding: 'utf8' }).trim())}.`,
    '',
    'Coverage is measured by pinned Vitest/V8 over the files loaded by each test suite; it is not a claim of exhaustive requirements coverage.',
    'Skipped tests are not passing evidence. PostgreSQL and Docker checks run in CI. Live paid-model/GitHub checks require separate opt-in.',
    '',
    'Model equivalents: core classifier, locator, context and guards. Controller equivalents: server stage services, repair loop and orchestrator.',
    '',
    '| Group | Passed/total | Lines | Branches | Functions | Statements |',
    '| --- | --- | --- | --- | --- | --- |',
    ...rows,
    '',
    ...files,
    '',
  ].join('\n'),
);
process.exitCode = failed ? 1 : 0;
