/**
 * Renders acceptance records (`docs/acceptance/AT-NN.md`) and the summary table
 * (`docs/acceptance/README.md`) from what one `npm run acceptance` run actually recorded.
 *
 * @packageDocumentation
 */
import type { NotRun, Verdict } from './record.js';

/** Build and environment of one acceptance run. */
export interface RunMeta {
  runAt: string;
  commit: string;
  branch: string;
  /** Uncommitted changes outside `docs/acceptance/` when the run started. */
  dirty: boolean;
  os: string;
  node: string;
  docker: string;
  postgres: string;
  oasdiff: string;
  database: string;
}

/** Everything recorded for one check. */
export interface CheckRecord {
  id: string;
  title: string;
  requirements: string;
  procedure: string;
  inputs: string[];
  steps: string[];
  notRun: NotRun[];
  verdict: Verdict;
  reason: string;
  transcript: string;
  durationMs: number;
  /** Whether `screenshots/<id>.png` was produced. */
  screenshot: boolean;
}

/** A check from SRS Appendix A that has no record in this increment. */
export interface PendingCheck {
  id: string;
  title: string;
  requirements: string;
  waitsFor: string;
}

/**
 * One line describing the environment, e.g. `macOS 26.6, Node v22.19.0, …`.
 * @param meta - Run metadata.
 */
export function environmentLine(meta: RunMeta): string {
  return `${meta.os}; Node ${meta.node}; Docker ${meta.docker}; ${meta.postgres}; oasdiff ${meta.oasdiff}`;
}

/**
 * The build line, e.g. "commit `abc1234` on `main` (clean working tree)".
 * @param meta - Run metadata.
 */
export function buildLine(meta: RunMeta): string {
  const tree = meta.dirty
    ? 'working tree had uncommitted changes outside docs/acceptance'
    : 'clean working tree apart from docs/acceptance';
  return `commit \`${meta.commit}\` on branch \`${meta.branch}\` (${tree})`;
}

const fence = (text: string) => {
  const longest = Math.max(2, ...[...text.matchAll(/`+/g)].map((m) => m[0].length));
  const ticks = '`'.repeat(longest + 1);
  return `${ticks}text\n${text.trimEnd()}\n${ticks}`;
};

/**
 * Markdown for one acceptance record.
 * @param rec - What the check recorded.
 * @param meta - Build and environment.
 */
export function renderRecord(rec: CheckRecord, meta: RunMeta): string {
  const lines = [
    `# ${rec.id} — ${rec.title}`,
    '',
    `**Result: ${rec.verdict}.** ${rec.reason}`,
    '',
    '<!-- Generated by `npm run acceptance` (scripts/acceptance/run.ts). Do not edit by hand. -->',
    '',
    '| Field | Value |',
    '| --- | --- |',
    `| Requirements | ${rec.requirements} |`,
    `| SRS procedure (Appendix A) | ${rec.procedure} |`,
    `| Build | ${buildLine(meta)} |`,
    `| Run at | ${meta.runAt} (took ${(rec.durationMs / 1000).toFixed(1)} s) |`,
    `| Environment | ${environmentLine(meta)} |`,
    `| Database | \`${meta.database}\`, dropped, re-created and migrated at the start of the run |`,
    '| Re-run | `npm run acceptance` |',
    '',
    '## Inputs',
    '',
    ...rec.inputs.map((i) => `- ${i}`),
    '',
    '## Steps actually run',
    '',
    ...rec.steps.map((s, i) => `${i + 1}. ${s}`),
    '',
    '## Actual output',
    '',
    `Full transcript: [output/${rec.id}.txt](output/${rec.id}.txt).`,
    '',
    ...(rec.screenshot
      ? [
          `Terminal screenshot (the transcript rendered as a terminal window; dashboard screenshots come with inc 14):`,
          '',
          `![${rec.id} terminal output](screenshots/${rec.id}.png)`,
          '',
        ]
      : ['No screenshot was produced on this run (the headless browser was not available).', '']),
    fence(rec.transcript),
    '',
    '## Not run on this build',
    '',
    ...(rec.notRun.length
      ? rec.notRun.map((n) => `- ${n.item}: ${n.reason}.`)
      : ['Nothing. Every part of the procedure ran.']),
    '',
    '## Result',
    '',
    `**${rec.verdict}.** ${rec.reason}`,
    '',
  ];
  return lines.join('\n');
}

/**
 * Markdown for `docs/acceptance/README.md`: the summary table.
 * @param records - The checks recorded in this run.
 * @param pending - Checks of Appendix A that wait for later increments.
 * @param meta - Build and environment.
 */
export function renderReadme(
  records: readonly CheckRecord[],
  pending: readonly PendingCheck[],
  meta: RunMeta,
): string {
  const rows = [
    ...records.map((r) => ({
      id: r.id,
      line: `| [${r.id}](${r.id}.md) | ${r.title} | ${r.requirements} | **${r.verdict}** | ${r.reason.replace(/\|/g, '\\|')} |`,
    })),
    ...pending.map((p) => ({
      id: p.id,
      line: `| ${p.id} | ${p.title} | ${p.requirements} | not recorded yet | Waits for ${p.waitsFor}. |`,
    })),
  ].sort((a, b) => a.id.localeCompare(b.id));
  const count = (v: Verdict) => records.filter((r) => r.verdict === v).length;
  return [
    '# Acceptance records (SRS Appendix A)',
    '',
    '<!-- Generated by `npm run acceptance` (scripts/acceptance/run.ts). Do not edit by hand. -->',
    '',
    'Each record shows a real execution: the build, the environment, the inputs, the steps that',
    'ran, the actual output, and the result. Results are computed by the script from the',
    'assertions that ran:',
    '',
    '- **PASS**: every part of the SRS procedure ran and every assertion held.',
    '- **PARTIAL**: every assertion that can run on this build held, but part of the procedure',
    '  needs an increment that is not built yet. The record lists exactly which part.',
    '- **FAIL**: an assertion did not hold, or the check could not run.',
    '',
    `Last run: ${meta.runAt}, ${buildLine(meta)}.`,
    `Environment: ${environmentLine(meta)}.`,
    '',
    `Summary: ${count('PASS')} PASS, ${count('PARTIAL')} PARTIAL, ${count('FAIL')} FAIL, ${pending.length} not recorded yet.`,
    '',
    '| Check | Title | Requirements | Result | Reason |',
    '| --- | --- | --- | --- | --- |',
    ...rows.map((r) => r.line),
    '',
    'Re-run everything with `npm run acceptance`. It needs Docker (for the sandbox), PostgreSQL',
    '(`npm run db:up`), and oasdiff 1.35.0. It drops and re-creates the `sma_acceptance_test`',
    'database, never the development database. Outputs go to [output/](output/) and terminal',
    'screenshots to [screenshots/](screenshots/).',
    '',
  ].join('\n');
}
